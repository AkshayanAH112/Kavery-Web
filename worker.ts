/**
 * The Worker entry: the OpenNext build (`.open-next/worker.js`, made by
 * `opennextjs-cloudflare build`) plus a Cron Trigger handler. wrangler.jsonc points
 * `main` here and runs `scheduled` once a minute.
 *
 * The scheduled handler does no work itself. It calls the app's own
 * /api/cron/push route through the Next handler, so that code runs with the same
 * bindings and request context as any other route. The route only accepts the call
 * with the one-time token passed in the env given to this request; no request from
 * outside can carry that.
 */
// The build output may not exist yet when this is type-checked, and has no types when it does.
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore -- generated by the build, so absent until the first build
import { default as handler } from "./.open-next/worker.js";

// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore -- generated by the build
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from "./.open-next/worker.js";

type Env = CloudflareEnv & { APP_URL: string };

const worker = {
  fetch: handler.fetch,

  async scheduled(_controller: ScheduledController, env: Env, ctx: ExecutionContext) {
    const token = `${crypto.randomUUID()}${crypto.randomUUID()}`;
    const request = new Request(new URL("/api/cron/push", env.APP_URL), { method: "POST", headers: { "x-cron-token": token } });
    const response: Response = await handler.fetch(request, { ...env, CRON_RUN_TOKEN: token }, ctx);
    // A failed run shows as an error in the Worker's logs and Cron events.
    if (!response.ok) throw new Error(`Scheduled notifications: ${response.status} ${await response.text()}`);
  },
};

export default worker;
